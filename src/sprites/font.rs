/// Lit pixels of a glyph inside its 8 by 8 cell as `(y, x)`.
pub fn lit(ch: char) -> Vec<(u32, u32)> {
    let Some((_, rows)) = GLYPHS.iter().find(|(c, _)| *c == ch) else {
        return vec![];
    };
    let mut out = vec![];
    for (y, row) in rows.split('/').enumerate() {
        for (x, b) in row.bytes().enumerate() {
            if b == b'#' {
                out.push((y as u32, x as u32 + 1));
            }
        }
    }
    out
}
